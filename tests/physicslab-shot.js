#!/usr/bin/env node
/* Physics Lab — every figure and every explorer, rendered from the shipped bundle and photographed.
   Fails on any page error, on a figure that draws nothing, and on an explorer that does not open
   once its prediction is made or that does not answer a slider with a changed readout.

   The figures are drawn from REAL questions: each one is generated by the domain code that serves
   it (physicslab-gen.php), so what is photographed is what a learner is asked about. */
const fs = require('fs'), path = require('path'), { spawn, execFileSync } = require('child_process');
const { waitForServer } = require('./_serve');
const ROOT = path.resolve(__dirname, '..'), PORT = process.env.PH_PORT || 8217;
const BASE = 'http://127.0.0.1:' + PORT, FIX = path.join(ROOT, 'tests', '_ph_fixture.html'), OUT = path.join(ROOT, 'tests', 'screens', 'physics');
function loadChromium() { for (const m of [process.env.PLAYWRIGHT_MODULE, 'playwright', 'playwright-core'].filter(Boolean)) { try { return require(m).chromium; } catch (_) {} } return null; }
(async () => {
  const chromium = loadChromium();
  if (!chromium) { console.log('⏭  physics lab shots: skipped (playwright not installed)'); process.exit(0); }
  fs.mkdirSync(OUT, { recursive: true });
  const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'dist', 'build-manifest.json'), 'utf8'));
  const SRC = JSON.parse(execFileSync('php', ['-r',
    'function db_row(){return null;} foreach (["labs","mathslab-map","mathslab-gen","mathslab-gen-upper","physicslab-map","physicslab-gen"] as $f) require "api/_lib/domain/$f.php"; lab_use("physics");'
    + '$by=[]; foreach (phy_forms() as $c => $fs) foreach ($fs as $i => $f) { $it = mlb_item($c, $i, 5); if (!empty($it["diagram"])) { $t=$it["diagram"]["type"]; $by[$t][] = ["comp"=>$c,"form"=>$i,"item"=>mlb_public($it)]; } }'
    + 'echo json_encode($by, JSON_UNESCAPED_UNICODE);'], { cwd: ROOT, encoding: 'utf8' }));
  const EXPL = execFileSync('node', ['-e', 'const s=require("fs").readFileSync("src/modules/mathslab/phy-visuals.jsx","utf8");const m=s.match(/const PHY_EXPLORERS = \\{([\\s\\S]*?)\\};/);console.log(JSON.stringify(m[1].match(/phy[A-Za-z]+(?=:)/g)));'], { cwd: ROOT, encoding: 'utf8' });
  const explorers = JSON.parse(EXPL);
  fs.writeFileSync(FIX, `<!doctype html><html><head><meta name="viewport" content="width=device-width, initial-scale=1">
<link rel="stylesheet" href="/dist/vendor/phosphor/phosphor.css"><link rel="stylesheet" href="/dist/styles.css"><link rel="stylesheet" href="/dist/styles-app.css">
<style>body{margin:0;background:#fff;padding:12px} .g{display:grid;grid-template-columns:repeat(auto-fill,minmax(340px,1fr));gap:14px} .g figure{margin:0;border:1px solid #e4e7f0;border-radius:12px;padding:10px} figcaption{font:12px sans-serif;color:#4a5272}</style>
</head><body><div id="root" class="stt-app"></div>
<script src="/dist/vendor/react.production.min.js"></script><script src="/dist/vendor/react-dom.production.min.js"></script>
<script src="/dist/data.js"></script><script src="/dist/photos.js"></script><script src="/dist/${manifest.bundle.file}"></script>
<script>
 var Q = new URLSearchParams(location.search), BY = ${JSON.stringify(SRC)};
 var C;
 if (Q.get('ex')) C = React.createElement('div', { className: 'mlb is-physics' }, React.createElement(MlbExplore, { comp: (PHY_EXPLORE[Q.get('ex')] || [])[0] }));
 else C = React.createElement('div', { className: 'mlb is-physics g' }, Object.keys(BY).map(function (t) { var x = BY[t][0];
   return React.createElement('figure', { key: t, 'data-type': t }, React.createElement(MlbDiagram, { d: x.item.diagram }), React.createElement('figcaption', null, t + ' · ' + x.comp + ' — ' + x.item.stem.slice(0, 90))); }));
 ReactDOM.createRoot(document.getElementById('root')).render(C);
</script></body></html>`);
  const srv = spawn('php', ['-S', '127.0.0.1:' + PORT, '-t', ROOT], { cwd: ROOT, stdio: 'ignore' });
  const browser = await chromium.launch();
  const problems = []; let shots = 0;
  try {
    await waitForServer(BASE + '/tests/_ph_fixture.html');
    // Every figure type, from a real question, on one sheet; each must draw shapes.
    for (const vp of [{ width: 1100, height: 900, name: 'figures' }, { width: 390, height: 844, name: 'figures-phone' }]) {
      const page = await browser.newPage({ viewport: { width: vp.width, height: vp.height }, deviceScaleFactor: 1 });
      const errs = []; page.on('pageerror', e => errs.push(String(e && e.message)));
      await page.goto(BASE + '/tests/_ph_fixture.html', { waitUntil: 'networkidle' });
      await page.waitForTimeout(400);
      const empty = await page.evaluate(() => Array.from(document.querySelectorAll('figure')).filter(f => { const s = f.querySelector('svg'); return !s || s.querySelectorAll('line,path,rect,circle,ellipse').length < 3; }).map(f => f.dataset.type));
      const n = await page.locator('figure').count();
      if (errs.length) problems.push(vp.name + ': ' + errs[0]);
      if (empty.length) problems.push(vp.name + ': figures that draw nothing: ' + empty.join(', '));
      if (n < Object.keys(SRC).length) problems.push(vp.name + ': only ' + n + ' of ' + Object.keys(SRC).length + ' figure types rendered');
      // Owner: "Make sure diagrams are the standard and they understand how it works" — every figure carries its reading guide, with a key.
      const noGuide = await page.evaluate(() => Array.from(document.querySelectorAll('figure')).filter(f => !f.querySelector('details.phy-read p') || !f.querySelector('.phy-key li svg')).map(f => f.dataset.type));
      if (noGuide.length) problems.push(vp.name + ': figures with no "How to read this diagram" key: ' + noGuide.join(', '));
      await page.evaluate(() => document.querySelectorAll('details.phy-read').forEach(d => { d.open = true; }));
      await page.screenshot({ path: path.join(OUT, vp.name + '.png'), fullPage: true }); shots++;
      await page.close();
    }
    // Every explorer: predict, then the explorer opens, a slider (or button) answers with a changed readout, and the verdict appears.
    for (const ex of explorers) {
      const page = await browser.newPage({ viewport: { width: 520, height: 1000 }, deviceScaleFactor: 1 });
      const errs = []; page.on('pageerror', e => errs.push(String(e && e.message)));
      await page.goto(BASE + '/tests/_ph_fixture.html?ex=' + ex, { waitUntil: 'networkidle' });
      try {
        await page.waitForSelector('.phy-predict-o', { timeout: 8000 });
        const hidden = await page.locator('.mlb-ex').count();
        await page.locator('.phy-predict-o').first().click();
        await page.waitForSelector('.mlb-ex', { timeout: 4000 });
        const before = await page.locator('.mlb-ex-out').innerText();
        const sl = page.locator('.mlb-ex input[type=range]').first();
        if (await sl.count()) { await sl.focus(); for (let k = 0; k < 4; k++) await page.keyboard.press('ArrowRight'); }
        else await page.locator('.mlb-ex .phy-seg-b:not(.is-on)').first().click();
        await page.waitForTimeout(250);
        const after = await page.locator('.mlb-ex-out').innerText();
        const verdict = await page.locator('.phy-predict-v').count();
        if (hidden) problems.push(ex + ': the explorer showed before a prediction was made');
        if (before === after) problems.push(ex + ': moving the first control changed nothing in the readout');
        if (!verdict) problems.push(ex + ': no verdict on the prediction after trying it');
      } catch (e) { problems.push(ex + ': ' + e.message.split('\n')[0]); }
      if (errs.length) problems.push(ex + ': ' + errs[0]);
      await page.screenshot({ path: path.join(OUT, 'ex-' + ex + '.png'), fullPage: true }); shots++;
      await page.close();
    }
  } finally { await browser.close(); srv.kill(); try { fs.unlinkSync(FIX); } catch (_) {} }
  if (problems.length) { console.log('❌ PHYSICS LAB SHOTS:\n  ' + problems.join('\n  ')); process.exit(1); }
  console.log('✅ PHYSICS LAB SHOTS: ' + shots + ' screens (' + Object.keys(SRC).length + ' figure types, ' + explorers.length + ' explorers) rendered clean into tests/screens/physics/');
})();
